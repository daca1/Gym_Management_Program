public class Cliente {

//    Criação do objeto Cliente;

    String nomeCliente;
    int idadeCliente;
    String moradaCliente;
    float pesoCliente_KG;
    int alturaCliente;
    String sexoCliente;


    public Cliente(String nomeCliente, int idadeCliente, String moradaCliente, float pesoCliente_KG, int alturaCliente, String sexoCliente) {
        this.nomeCliente = nomeCliente;
        this.idadeCliente = idadeCliente;
        this.moradaCliente = moradaCliente;
        this.pesoCliente_KG = pesoCliente_KG;
        this.alturaCliente = alturaCliente;
        this.sexoCliente = sexoCliente;
    }


}
