public class Cliente {

//    Criação do objeto Cliente;

    private String nome_cliente;
    private int idade_cliente;
    private String morada_cliente;
    private float peso_cliente;
    private int altura_CM_cliente;
    private String sexo_cliente;


    public String getNome_cliente() {
        return nome_cliente;
    }

    public void setNome_cliente(String nome_cliente) {
        this.nome_cliente = nome_cliente;
    }

    public int getIdade_cliente() {
        return idade_cliente;
    }

    public void setIdade_cliente(int idade_cliente) {
        this.idade_cliente = idade_cliente;
    }

    public String getMorada_cliente() {
        return morada_cliente;
    }

    public void setMorada_cliente(String morada_cliente) {
        this.morada_cliente = morada_cliente;
    }

    public float getPeso_cliente() {
        return peso_cliente;
    }

    public void setPeso_cliente(float peso_cliente) {
        this.peso_cliente = peso_cliente;
    }

    public int getAltura_CM_cliente() {
        return altura_CM_cliente;
    }

    public void setAltura_CM_cliente(int altura_CM_cliente) {
        this.altura_CM_cliente = altura_CM_cliente;
    }

    public String getSexo_cliente() {
        return sexo_cliente;
    }

    public void setSexo_cliente(String sexo_cliente) {
        this.sexo_cliente = sexo_cliente;
    }
}
